#!/usr/bin/env bash
# Regenerate samples/: export every reference design, run the Blender bridge + full round-trip
# check, then keep the light-weight files in the repo (everything else is reproducible).
# Needs: node deps, `pip install bpy usd-core`.
set -euo pipefail
cd "$(dirname "$0")/.."
TMP=$(mktemp -d)
npx tsx tools/cli.ts samples "$TMP"
python3 tools/roundtrip_check.py "$TMP"/*/ | grep ROUNDTRIP
rm -rf samples && mkdir -p samples
for d in "$TMP"/*/; do
  n=$(basename "$d")
  mkdir -p "samples/$n"
  cp "$d/$n.badmech.json" "$d/$n.rig.json" "$d/$n.glb" "$d/$n.fbx" "$d/$n.validation.json" \
     "$d/$n.bridge_report.json" "$d/roundtrip_report.json" "$d/README.txt" "samples/$n/"
done
python3 - <<'PY'
import json, glob, os
rows = []
for f in sorted(glob.glob('samples/*/roundtrip_report.json')):
    r = json.load(open(f))
    ok = lambda k: '✅' if r[k]['ok'] else '❌'
    rows.append(f"| {r['mech']} | {r['family']} | {r['heightM']} m | {ok('glb')} | {ok('glb_lod1')}{ok('glb_lod2')} | {ok('fbx')} {r['fbx']['boneCount']} bones | {ok('fbx_pose')} | {ok('usd')} | {ok('obj')} | {r['glb']['maxPosErrorM']:.1e} m |")
hdr = "| Mech | Family | Height | GLB→Blender | LOD1/2 | FBX re-import | FBX pose | USD (pxr + Blender) | OBJ | worst pivot error |\n|---|---|---|---|---|---|---|---|---|---|\n"
open('samples/ROUNDTRIP.md', 'w').write("# Round-trip results\n\nGenerated by `tools/make_samples.sh` (Blender " + __import__('bpy').app.version_string + ", Pixar USD).\n\n" + hdr + "\n".join(rows) + "\n")
print(open('samples/ROUNDTRIP.md').read())
PY
rm -rf "$TMP"
